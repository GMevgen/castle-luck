  D.residentScene = function (id, lvl, opt) {
    var r = D.RESIDENTS[id]; if (!r) return null;
    opt = opt || {};
    var key = opt.locked ? 'lock' : opt.building ? 'build' : lvl <= 0 ? 'empty' : 't' + D.bldTier(lvl);
    var vars = r[key] || r.empty || r.t1, k = opt.k || 0;
    var b = D.BLD_BY_ID[id];
    return { img: D.ISO.map, sprite: 'img/iso/' + (lvl > 0 ? D.bldSprite(id, lvl) : 'ruins') + '.webp', resident: true,
      kicker: b.name, title: opt.locked ? 'Откроется на ' + b.unlock + ' ур.' : lvl > 0 ? 'Уровень ' + lvl : 'Не построено',
      lines: vars[(lvl + k) % vars.length] };
  };

