self.addEventListener('install', function (e) {
  e.waitUntil(caches.open(CACHE).then(function (c) {
    // cache: 'reload' — мимо HTTP-кэша, чтобы не положить в новую версию старый файл
    return Promise.all(ASSETS.map(function (u) { return fetch(new Request(u, { cache: 'reload' })).then(function (r) { if (!r.ok) throw new Error(u + ' ' + r.status); return c.put(u, r); }); }));
  }).then(function () {
    // самая первая установка — сразу активируемся; обновление ждёт команды игрока
    return self.registration.active ? null : self.skipWaiting();
  }));
});

self.addEventListener('activate', function (e) {
  e.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (k) { return k.indexOf('castle-luck-') === 0 && k !== CACHE; }).map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }));
});

self.addEventListener('message', function (e) { if (e.data && e.data.type === 'SKIP_WAITING') self.skipWaiting(); });

self.addEventListener('fetch', function (e) {
  var req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // запуск с экрана «Домой» / перезагрузка: всегда index.html из кэша (офлайн тоже)
    e.respondWith(caches.open(CACHE).then(function (c) { return c.match('./').then(function (r) { return r || c.match('index.html'); }); }).then(function (r) { return r || fetch(req); }));
    return;
  }
  e.respondWith(caches.open(CACHE).then(function (c) {
    return c.match(req, { ignoreSearch: true }).then(function (r) {
      return r || fetch(req).then(function (resp) { if (resp.ok && resp.type === 'basic') c.put(req, resp.clone()); return resp; });
    });
  }));
});
